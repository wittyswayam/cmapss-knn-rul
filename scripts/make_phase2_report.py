"""Write results/phase2/FD001_phase2_report.md from the saved experiment outputs.

Every number in the report is read from files written by run_phase2_experiments.py.
"""

from __future__ import annotations

import _paths  # noqa: F401

import json
import sys

import pandas as pd

from cmapss_knn.config import load_config


def md(df: pd.DataFrame, fmt: str = "{:.3f}") -> str:
    head = "| " + " | ".join(str(c) for c in df.columns) + " |"
    sep = "|" + "|".join(["---"] * len(df.columns)) + "|"
    rows = ["| " + " | ".join(fmt.format(v) if isinstance(v, float) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main() -> int:
    cfg = load_config()
    d = cfg.paths.results_dir / "phase2"
    r = json.loads((d / "phase2_summary.json").read_text(encoding="utf-8"))
    s = r["setup"]
    L = ["# FD001 Phase 2 results (generated)", "",
         "Generated by `scripts/make_phase2_report.py` from `results/phase2/`. The official test set was not used.", "",
         "## Protocol", "",
         f"- {s['tuning_engines']} tuning engines ({s['tuning_rows']} rows) and {s['holdout_engines']} holdout engines ({s['holdout_rows']} rows), split by engine with seed {cfg.seed}.",
         f"- {cfg.validation.n_folds}-fold CV over engines on the tuning set (validation engines per fold: {s['fold_validation_engines']}).",
         f"- Grid: {s['n_configurations']} configurations (sensor config x baseline x window x history strategy x metric x weighting x k).",
         f"- Engine-level evaluation: {cfg.validation.eval_cutoffs_per_engine} random cutoffs per engine from cycle {cfg.validation.eval_min_cutoff} on ({s['engine_level_points_tuning']} points in tuning, {s['engine_level_points_holdout']} in holdout).",
         f"- Short-history stress points: cycles {list(cfg.validation.stress_cutoffs)}. Window-level evaluation uses every cycle of every validation engine.",
         "- `_clip` metrics compare with the RUL clipped at 125; `_raw` metrics compare with the true RUL. Selection criterion: engine-level RMSE vs clipped RUL (mean over folds).", ""]

    cols = ["eng_rmse_clip_mean", "eng_rmse_clip_std", "eng_mae_clip_mean", "eng_bias_clip_mean", "eng_nasa_clip_mean", "eng_rmse_raw_mean", "win_rmse_clip_mean", "stress_rmse_clip_mean"]
    desc = ["sensor_config", "baseline", "window", "history", "metric", "weights", "k", "n_features"]
    best = pd.DataFrame([{"model": "best A (s6 kept)", **{c: r["best_A"][c] for c in desc + cols}}, {"model": "best B (s6 removed)", **{c: r["best_B"][c] for c in desc + cols}}])
    c = r["constant_baseline_cv_mean"]
    const = {"model": "constant (training mean)", **{k: "" for k in desc}, "eng_rmse_clip_mean": c["eng_rmse_clip"], "eng_rmse_clip_std": "", "eng_mae_clip_mean": c["eng_mae_clip"], "eng_bias_clip_mean": c["eng_bias_clip"],
             "eng_nasa_clip_mean": c["eng_nasa_clip"], "eng_rmse_raw_mean": c["eng_rmse_raw"], "win_rmse_clip_mean": c["win_rmse_clip"], "stress_rmse_clip_mean": c["stress_rmse_clip"]}
    best = pd.concat([best, pd.DataFrame([const])], ignore_index=True)
    L += ["## Best configurations (cross-validation, tuning engines)", "", md(best), "",
          "`eng_rmse_clip_std` is the standard deviation over the 5 folds. `eng_nasa_clip_mean` is the mean (not sum) NASA score per prediction.", ""]

    top = pd.read_csv(d / "top15_configurations.csv")
    L += ["## Ten best configurations", "", md(top.head(10)[desc[:7] + ["eng_rmse_clip_mean", "eng_rmse_clip_std", "win_rmse_clip_mean", "stress_rmse_clip_mean"]]), ""]

    def effect_table(stats: dict, labels: dict | None = None) -> pd.DataFrame:
        rows = []
        for m, v in stats.items():
            if m.startswith(("eng_rmse_clip", "win_rmse_clip", "stress_rmse_clip")):
                rows.append({"metric": m.replace("_mean", ""), "matched configs": v["matched_configs"], "mean diff": v["mean_diff"], "median diff": v["median_diff"], "share where 'other' is better": v["share_other_better"], "min diff": v["min_diff"], "max diff": v["max_diff"]})
        return pd.DataFrame(rows)

    L += ["## Sensor configuration: A (drop constant sensors) vs B (also drop s6)", "",
          "Difference = B - A over matched configurations (everything else identical); negative means removing s6 lowers the error.", "",
          "### All matched configurations", "", md(effect_table(r["s6_paired_stats"])), "", "### Split by baseline option", ""]
    for b, st in r["s6_paired_by_baseline"].items():
        L += [f"baseline = {b}", "", md(effect_table(st)), ""]
    L += ["### Per-fold, best-A hyper-parameters, with (A) and without (B) s6", "", md(pd.DataFrame(r["s6_fold_pairs_bestA_hparams"]).rename(columns={"base": "A rmse", "other": "B rmse", "diff": "B - A"})), "",
          "### Permutation control (best A configuration for each baseline option; engine-level RMSE vs clipped RUL)", "",
          md(pd.read_csv(d / "s6_permutation_control.csv")), "",
          "`rmse_shuffled_s6_*`: s6 feature columns shuffled across rows (10 shuffles). Shuffling keeps the distribution of s6 but destroys its relation to the engine and to time.", "",
          "### s6 as the only sensor", "", f"Ties: {r['s6_only_ties']}. CV mean (best A hyper-parameters): engine-level RMSE vs clipped {r['s6_only_cv_mean']['eng_rmse_clip']:.2f}, window-level {r['s6_only_cv_mean']['win_rmse_clip']:.2f}. "
          "With this many identical feature vectors the neighbour choice inside a tie group is arbitrary, so this number should not be read as a measure of s6's information.", "",
          "### How often s6 reads its lower value (21.60), by remaining useful life (tuning engines)", "", md(pd.read_csv(d / "s6_low_value_rate_by_rul.csv")), "", f"Summary: {r['s6_low_value_summary']}", ""]

    L += ["## Per-engine causal baselining vs raw sensors", "", "Difference = causal - none over matched configurations.", "", md(effect_table(r["baseline_paired_stats"])), "",
          "Best engine-level RMSE per window length:", "", md(pd.DataFrame([{"window": w, **v} for w, v in r["baseline_best_by_window"].items()])), "",
          "Per fold at the best-A hyper-parameters (base = causal baseline, other = none):", "", md(pd.DataFrame(r["baseline_fold_pairs_best"]).rename(columns={"base": "causal rmse", "other": "none rmse", "diff": "none - causal"})), ""]

    L += ["## Short-history strategy: adaptive window vs pad_first", "", "Difference = pad_first - adaptive over matched configurations.", "", md(effect_table(r["history_paired_stats"])), "",
          "By window length (stress = mean RMSE at cutoffs 5, 10, 20 over the whole grid; eng = best engine-level RMSE):", "",
          md(pd.DataFrame([{"window": w, "adaptive stress": v["adaptive"]["stress_rmse_mean"], "pad_first stress": v["pad_first"]["stress_rmse_mean"], "adaptive eng best": v["adaptive"]["eng_rmse_best"], "pad_first eng best": v["pad_first"]["eng_rmse_best"]} for w, v in r["history_by_window"].items()])), ""]

    L += ["## Exact duplicate feature vectors (best A configuration, CV fold 0 training rows)", "", f"{r['duplicate_feature_rows_best_config_fold0']}", ""]

    comp = pd.read_csv(d / "backend_comparison_cv.csv")
    L += ["## Scratch vs scikit-learn on the CV folds", "",
          f"{r['backend_comparison_total_predictions']} predictions compared over {len(comp)} fold runs; maximum absolute difference {r['backend_comparison_max_abs_diff']:.3g}; predictions differing by more than 1e-9: {r['backend_comparison_n_diff_gt_1e-9']}. "
          f"Mean fit+predict time per fold: scratch {r['backend_seconds']['scratch_mean']:.1f} s, scikit-learn (brute force) {r['backend_seconds']['sklearn_mean']:.2f} s.", "", md(comp), ""]

    h = pd.read_csv(d / "holdout_results.csv")
    L += ["## Exploratory development holdout (20 engines)", "", "This holdout was evaluated more than once after the search grid changed. It is **not an independent test** and should not be quoted as one; see docs/EVALUATION_PROTOCOL.md.", "",
          md(h[["model", "max_abs_diff_scratch_vs_sklearn", "eng_rmse_clip", "eng_mae_clip", "eng_bias_clip", "eng_nasa_clip", "eng_rmse_raw", "win_rmse_clip", "stress_rmse_clip", "n_eng", "n_win"]]), "",
          "Both the scikit-learn and the from-scratch backend were run for each KNN model; `max_abs_diff_scratch_vs_sklearn` is their largest prediction difference.", ""]
    (d / "FD001_phase2_report.md").write_text("\n".join(L), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())

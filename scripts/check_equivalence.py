"""Measure how closely the from-scratch KNN matches scikit-learn.

Usage (from the repository root):
    python scripts/check_equivalence.py
Writes results/phase2/equivalence_cases.csv and equivalence_report.md.
Real FD001 features are included if the raw data is available.
"""

from __future__ import annotations

import _paths  # noqa: F401

import logging
import sys

import numpy as np
from sklearn.preprocessing import StandardScaler

from cmapss_knn.config import load_config
from cmapss_knn.data.ingestion import read_subset
from cmapss_knn.data.schema import ID_COLUMN, RUL_CLIPPED_COLUMN
from cmapss_knn.exceptions import CMAPSSError
from cmapss_knn.experiments import phase2 as p2
from cmapss_knn.experiments.equivalence import run_equivalence, summarise_equivalence
from cmapss_knn.features import SensorSelector, WindowConfig, build_features, feature_column_indices
from cmapss_knn.logging_utils import setup_logging

logger = logging.getLogger("check_equivalence")


def _real_data(cfg):
    subset = read_subset("FD001", cfg.paths.raw_data_dir, cfg.archive_name)
    setup = p2.make_setup(subset.train, cfg)
    df = setup.tuning
    table = build_features(df, WindowConfig(30, cfg.features.stats, "adaptive", "causal", cfg.features.baseline_cycles))
    tru, vau = setup.folds[0]
    Xtr, Xva, tr, va, _ = p2._fold_arrays(table, df, tru, vau, "A")
    ytr = df[RUL_CLIPPED_COLUMN].to_numpy()[tr]
    return Xtr, ytr, Xva[::6]  # every 6th validation row keeps the slow scratch model quick


def main() -> int:
    cfg = load_config()
    setup_logging(cfg.log_level, cfg.paths.logs_dir / "check_equivalence.log")
    try:
        real = _real_data(cfg)
    except CMAPSSError as exc:
        logger.warning("Real data not available (%s); running synthetic cases only.", exc)
        real = None
    cases = run_equivalence(real)
    out = cfg.paths.results_dir / "phase2"
    out.mkdir(parents=True, exist_ok=True)
    cases.to_csv(out / "equivalence_cases.csv", index=False)
    summary = summarise_equivalence(cases)
    summary.to_csv(out / "equivalence_summary.csv")
    print(summary.to_string(float_format=lambda v: f"{v:.3g}"))

    lines = ["# Scratch KNN vs scikit-learn: measured equivalence", "",
             "Generated by `scripts/check_equivalence.py`. Each configuration fits both models on identical data and compares",
             "predictions, neighbour sets and neighbour distances.", "", "| case | configurations | max abs prediction diff | configs with any diff > 1e-9 | min share of identical neighbour sets | max abs distance diff |", "|---|---|---|---|---|---|"]
    for case, r in summary.iterrows():
        lines.append(f"| {case} | {int(r['configurations'])} | {r['max |pred diff|']:.3g} | {int(r['configs with any pred diff > 1e-9'])} | {r['min share of identical neighbour sets']:.3f} | {r['max |distance diff|']:.3g} |")
    diffs = cases[cases["n_pred_diff_gt_1e-9"] > 0]
    lines += ["", "## Configurations with prediction differences above 1e-9", ""]
    if diffs.empty:
        lines.append("None.")
    else:
        lines += ["| case | metric | weights | sklearn algorithm | k | queries differing | max abs diff |", "|---|---|---|---|---|---|---|"]
        lines += [f"| {r.case} | {r.metric} | {r.weights} | {r.sklearn_algorithm} | {r.k} | {r['n_pred_diff_gt_1e-9']} of {r.n_queries} | {r.max_abs_pred_diff:.3g} |" for _, r in diffs.iterrows()]
    (out / "equivalence_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
